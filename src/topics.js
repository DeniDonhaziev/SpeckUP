export function getPublicCategories() {
  return Object.entries(TOPIC_CATEGORIES).map(([id, value]) => ({
    id,
    title: value.title,
    emoji: value.emoji,
    count: value.topics.length
  }));
}

export function getRandomTopic(category = "everyday", exclude = "") {
  const selected = TOPIC_CATEGORIES[category] ?? TOPIC_CATEGORIES.everyday;
  const candidates = selected.topics.filter((topic) => topic !== exclude);
  const pool = candidates.length ? candidates : selected.topics;
  return pool[Math.floor(Math.random() * pool.length)];
}
